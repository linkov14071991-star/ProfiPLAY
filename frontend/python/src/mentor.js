// Дней до ближайшего наступления даты месяц/день.
export function daysToExam(month, day) {
  if (!month || !day) return null;
  const now = new Date();
  const y = now.getFullYear();
  let target = new Date(y, month - 1, day);
  // если дата в этом году уже прошла — берём следующий год
  const today0 = new Date(y, now.getMonth(), now.getDate());
  if (target < today0) target = new Date(y + 1, month - 1, day);
  return Math.max(0, Math.round((target - today0) / 86400000));
}
