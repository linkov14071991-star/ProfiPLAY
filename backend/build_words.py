def main():
    data = json.loads(WORDS_FILE.read_text(encoding="utf-8"))
    # добавляем эмодзи существующим словам информатики
    for lv in ("easy", "medium", "hard"):
        for item in data["informatika"][lv]:
            if isinstance(item, dict):
                item.setdefault("emoji", INF_EMOJI.get(item["word"], ""))
    data["matematika"] = MATEMATIKA
    data["fizika"] = FIZIKA
    WORDS_FILE.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    # отчёт
    for cat, levels in data.items():
        total = sum(len(v) for v in levels.values())
        no_emoji = sum(1 for v in levels.values() for it in v if isinstance(it, dict) and not it.get("emoji"))
        print(f"{cat}: {total} слов, без эмодзи: {no_emoji}")


if __name__ == "__main__":
    main()
