def classify(theme, text):
    t = text.lower()
    for name, kws in SUBTOPICS.get(theme, []):
        for kw in kws:
            if kw in t:
                return name
    return "Прочее"


def theme_counts(bank, themes):
    out = {}
    for th in themes:
        if th not in bank:
            continue
        levels = {d: len(bank[th].get(d, [])) for d in ("easy", "medium", "hard")}
        out[th] = levels
    return out


def subtopic_report(theme):
    pool = []
    for d in ("easy", "medium", "hard"):
        for it in Q[theme].get(d, []):
            pool.append(it["q"])
    buckets = {}
    for name, _ in SUBTOPICS[theme]:
        buckets[name] = 0
    buckets["Прочее"] = 0
    for text in pool:
        buckets[classify(theme, text)] += 1
    return buckets, len(pool)


